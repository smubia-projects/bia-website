// One-off: turn the raw _intake photos into small, uniform webp tiles for the
// home-page HeroGlobe. Run with:  node scripts/optimize-globe-images.mjs
//
// Each source (multi-MB PNG, ~1920x2560) becomes a 512x512 webp (~25-35KB),
// square-cropped with sharp's "attention" strategy so faces survive the crop.
// Also (re)writes app/components/heroGlobeImages.ts — the list the component reads.

import sharp from "sharp";
import { readdir, mkdir, stat, writeFile } from "node:fs/promises";
import path from "node:path";

const SRC_DIR = "_intake";
const OUT_DIR = path.join("public", "images", "home", "globe");
const MANIFEST = path.join("app", "components", "heroGlobeImages.ts");
const SIZE = 512;
const QUALITY = 78;
const EXT = new Set([".jpg", ".jpeg", ".png", ".webp"]);

async function walk(dir) {
  const out = [];
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) out.push(...(await walk(full)));
    else if (EXT.has(path.extname(entry.name).toLowerCase())) out.push(full);
  }
  return out;
}

const mb = (n) => (n / 1048576).toFixed(2) + " MB";
const kb = (n) => (n / 1024).toFixed(0) + " KB";

const sources = (await walk(SRC_DIR)).sort();
await mkdir(OUT_DIR, { recursive: true });

let before = 0;
let after = 0;
const webPaths = [];

for (let i = 0; i < sources.length; i++) {
  const src = sources[i];
  const name = `tile-${String(i + 1).padStart(2, "0")}.webp`;
  const dest = path.join(OUT_DIR, name);

  before += (await stat(src)).size;
  await sharp(src)
    .resize(SIZE, SIZE, { fit: "cover", position: sharp.strategy.attention })
    .webp({ quality: QUALITY })
    .toFile(dest);
  const outSize = (await stat(dest)).size;
  after += outSize;

  webPaths.push(`/images/home/globe/${name}`);
  console.log(`${name}  ${kb(outSize).padStart(7)}   ←  ${path.basename(src)}`);
}

const ts = `// AUTO-GENERATED by scripts/optimize-globe-images.mjs — do not edit by hand.
// Optimized candid photos that ride the home-page HeroGlobe.
export const heroGlobeImages = [
${webPaths.map((p) => `  "${p}",`).join("\n")}
];
`;
await writeFile(MANIFEST, ts, "utf8");

console.log("\n────────────────────────────");
console.log(`tiles:   ${sources.length}`);
console.log(`before:  ${mb(before)}`);
console.log(`after:   ${mb(after)}  (${kb(after / sources.length)} avg)`);
console.log(`saved:   ${(100 - (after / before) * 100).toFixed(1)}%`);
console.log(`manifest: ${MANIFEST}`);
